/**
 * build-artifact.mjs - regenerate the committed contract artifacts from the
 * solc compiler output in out/.
 *
 * Run after editing contracts/*.sol:
 *   npm run compile
 *
 * This keeps the committed artifacts (ABI + creation bytecode) exactly in
 * sync with the Solidity sources: no hand-copying, no drift.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");

const CONTRACTS = [
  { file: "QuantumFlip", varPrefix: "quantumFlip" },
  { file: "StreakBadge", varPrefix: "streakBadge" },
];

for (const { file, varPrefix } of CONTRACTS) {
  const abiPath = path.join(root, "out", `contracts_${file}_sol_${file}.abi`);
  const binPath = path.join(root, "out", `contracts_${file}_sol_${file}.bin`);

  const abi = JSON.parse(fs.readFileSync(abiPath, "utf8"));
  const bin = fs.readFileSync(binPath, "utf8").trim();
  if (!/^[0-9a-fA-F]+$/.test(bin) || bin.length === 0) {
    throw new Error(`Unexpected bytecode output from solc for ${file}.`);
  }

  const header = `// AUTO-GENERATED by scripts/build-artifact.mjs from contracts/${file}.sol\n// (solc 0.8.24, --optimize). Do not edit by hand; run \`npm run compile\`.\n`;
  const body =
    header +
    `export const ${varPrefix}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\nexport const ${varPrefix}Bytecode = "0x${bin}" as const;\n`;

  fs.writeFileSync(path.join(root, "contracts", `${file}.artifact.ts`), body);
  console.log(`Wrote contracts/${file}.artifact.ts (${abi.length} ABI entries, ${bin.length / 2} bytes of bytecode).`);
}
